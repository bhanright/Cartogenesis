        }
        finding("realm borders", Detector.RIGHT_ANGLES, F.REALM_BORDER_CORNERS)
        for (detector in listOf(Detector.ISOTROPY, Detector.FACETS, Detector.ALIGNED_SIDE)) finding("isotherms", detector, F.ISOTHERMS_ALONG_ROWS)
