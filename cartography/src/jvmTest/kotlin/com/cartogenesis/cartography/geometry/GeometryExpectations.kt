/**
 * What the geometry censuses expect of today's worlds: which finding each layer's violations of
 * each detector record, and at each grid, the signature of every known violation and every clause
 * too small to measure. The census prints its own `GEOMETRY RECORD` lines in this form.
 */
internal object GeometryExpectations {

    /** The finding a violation records, by layer and detector, at every grid. */
    fun findings(expected: Expectations) = with(expected) {
        finding("coast as inked", Detector.FACING, F.COAST_INK)
        for (layer in listOf("ice occupancy", "ice sheet ground", "ice carving", "ice as drawn", "ice surface")) {
            finding(layer, Detector.ALIGNED_SIDE, F.ICE_EDGE_ALONG_A_ROW)
            finding(layer, Detector.FACETS, F.ICE_EDGE_ALONG_A_ROW)
        }
        // The ice's crease is two of its straight runs meeting (718106 at 2048).
        finding("ice as drawn", Detector.CREASES, F.ICE_EDGE_ALONG_A_ROW)
        finding("ice occupancy", Detector.RIGHT_ANGLES, F.ICE_EDGE_CORNERS)
        for (layer in listOf("ice sheet ground", "ice carving", "ice as drawn")) {
            finding(layer, Detector.RIGHT_ANGLES, F.ICE_EDGE_CORNERS)
            finding(layer, Detector.CORNER_RATE, F.ICE_EDGE_CORNERS)
        }
        finding("ice carving", Detector.ARCS, F.ICE_ARCS)
        finding("ice surface", Detector.ARCS, F.ICE_ARCS)
        // A valley basin is the ice's cut in a valley, so a round rim to one is the same finding.
        finding("valley basins", Detector.ARCS, F.ICE_ARCS)
        finding("valley glaciers", Detector.CREASES, F.VALLEY_GLACIER_HAIRPIN)
        finding("delta lobes", Detector.ARCS, F.DELTA_LOBES_ROUND)
        for (layer in listOf("coast", "coast as drawn")) {
            finding(layer, Detector.ARCS, F.DELTA_LOBES_ROUND)
            finding(layer, Detector.FACETS, F.COAST_STRAIGHT)
        }
        finding("coast as drawn", Detector.RIGHT_ANGLES, F.COAST_SQUARE_NOTCH)
        finding("lake fans", Detector.ARCS, F.LAKE_FANS_STAMPED)
        finding("river courses", Detector.ARCS, F.RIVER_ARC)
        // The drawn rivers are a selection of the traced courses, so an arc in one is the same arc
        // in the other where the pane keeps it: seed 1234's at 512 once the ground's ruler redrew it.
        finding("rivers as drawn", Detector.ARCS, F.RIVER_ARC)
        finding("river courses", Detector.RIGHT_ANGLES, F.RIVER_SQUARE_CORNERS)
        finding("rivers as drawn", Detector.RIGHT_ANGLES, F.RIVER_SQUARE_CORNERS)
        finding("isobaths", Detector.FACETS, F.SEA_FLOOR_RAMPS)
        finding("isobaths", Detector.CREASES, F.SEA_FLOOR_RAMPS)
        finding("isobaths", Detector.RIGHT_ANGLES, F.ISOBATH_SQUARE_CORNER)
        finding("isobaths", Detector.ARCS, F.SEAMOUNT_CONES)
        finding("terrain contours", Detector.FACETS, F.STRAIGHT_RANGE_FRONTS)
        finding("terrain contours", Detector.ARCS, F.TERRAIN_ARC)
        finding("terrain contours", Detector.RIGHT_ANGLES, F.LEVEL_LINE_CORNER_AT_THE_ICE)
        finding("isotherms", Detector.RIGHT_ANGLES, F.LEVEL_LINE_CORNER_AT_THE_ICE)
        finding("biome edges", Detector.RIGHT_ANGLES, F.BIOME_EDGE_CORNER)
        finding("biome edges", Detector.CREASES, F.BIOME_EDGE_HAIRPINS)
        for (detector in listOf(Detector.ALIGNED_SIDE, Detector.FACETS, Detector.RIGHT_ANGLES, Detector.CREASES)) {
            finding("peoples' borders", detector, F.PEOPLES_BORDERS_ON_THE_GRID)
        }
        finding("realm borders", Detector.RIGHT_ANGLES, F.REALM_BORDER_CORNERS)
        // A realm border's straight run seen along a grid bearing, or as two runs meeting in a
        // crease, is the same straight border (42 and 59758 at 2048).
        for (detector in listOf(Detector.FACETS, Detector.ALIGNED_SIDE, Detector.CREASES)) {
            finding("realm borders", detector, F.REALM_BORDERS_STRAIGHT)
        }
        finding("realm borders", Detector.ARCS, F.REALM_BORDER_ARC)
        // Once the partition was on the ground a boundary's straight run is as often along a grid
        // bearing as not, and the aligned-side detector sees those (docs/DESIGN_LEDGER.md, Fix 2).
        finding("plate boundaries", Detector.FACETS, F.PLATE_BOUNDARIES_STRAIGHT)
        finding("plate boundaries", Detector.ALIGNED_SIDE, F.PLATE_BOUNDARIES_STRAIGHT)
        finding("plate boundaries", Detector.ARCS, F.PLATE_BOUNDARY_ARC)
        finding("isotherms", Detector.ISOTROPY, F.ISOTHERMS_ALONG_ROWS)
        finding("isotherms", Detector.FACETS, F.ISOTHERMS_ALONG_ROWS)
        finding("isohyets", Detector.CREASES, F.ISOHYET_CREASE)
        // The rectangle and the square corners are the same banding seen by two more detectors: on
        // seed 7 at 512, a band of anomaly 2,232 km long and 132 km deep along a row, its ends
        // turning square where the band meets the one beside it (docs/DESIGN_LEDGER.md, Fix 2). The
        // corner rate counts those square ends: seed 7 at 512 read over it once a lake falls with
        // its outlet (Fix 3b's review round).
        for (detector in listOf(
            Detector.ALIGNED_SIDE, Detector.FACETS, Detector.CREASES, Detector.RECTANGLE, Detector.RIGHT_ANGLES,
            Detector.CORNER_RATE
        )) {
            finding("sea temperature anomaly", detector, F.ANOMALY_ALONG_ROWS)
        }
    }


